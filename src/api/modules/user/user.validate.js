const Joi = require("joi");

const updateUserSchema = Joi.object({
  name: Joi.string().trim().max(30).min(3),
  username: Joi.string().trim().lowercase().min(3).max(30),
  role: Joi.string().valid("user", "admin").default("user"),
  login: Joi.string().trim().allow(""),
  id: Joi.number().default(0),
  node_id: Joi.string().trim().allow(""),
  avatar_url: Joi.string().uri().allow(""),
  gravatar_id: Joi.string().trim().allow(""),
  url: Joi.string().uri().allow(""),
  html_url: Joi.string().uri().allow(""),
  linkedin_url: Joi.string().uri().allow(""),
  followers_url: Joi.string().uri().allow(""),
  following_url: Joi.string().uri().allow(""),
  gists_url: Joi.string().uri().allow(""),
  starred_url: Joi.string().uri().allow(""),
  subscriptions_url: Joi.string().uri().allow(""),
  organizations_url: Joi.string().uri().allow(""),
  repos_url: Joi.string().uri().allow(""),
  events_url: Joi.string().uri().allow(""),
  received_events_url: Joi.string().uri().allow(""),
  type: Joi.string().valid("User", "Organization").default("User"),
  site_admin: Joi.boolean().default(false),
  company: Joi.string().trim().allow(""),
  blog: Joi.string().uri().allow(""),
  location: Joi.string().trim().allow(""),
  hireable: Joi.boolean().default(false),
  bio: Joi.string().trim().allow(""),
  twitter_username: Joi.string().trim().allow(""),
  public_repos: Joi.number().integer().min(0).default(0),
  public_gists: Joi.number().integer().min(0).default(0),
  followers: Joi.number().integer().min(0).default(0),
  following: Joi.number().integer().min(0).default(0),
  created_at: Joi.date().default(Date.now),
  updated_at: Joi.date().default(Date.now),
});

module.exports = updateUserSchema;
